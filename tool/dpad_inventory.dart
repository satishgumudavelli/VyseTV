// Writes docs/dpad/inventory.md: every tappable, overlay, text box, drag and hover spot in the
// interface, by file, with the phase of the D-pad plan that deals with the file.
//
//   dart run tool/dpad_inventory.dart
//
// Run it again at the end of a phase: the "raw tap" list is what is left to convert.
import 'dart:io';

import '../test/dpad/bed/source_scan.dart';

const _columns = ['onTap', 'pressable', 'material', 'raw tap', 'overlay', 'text box', 'hover', 'drag', 'long press', 'arrow keys', 'key handler', 'autofocus', 'focus node', 'passed over'];

void main() {
  final all = scanInterface();
  final out = StringBuffer()
    ..writeln('# D-pad inventory')
    ..writeln()
    ..writeln('Generated by `dart run tool/dpad_inventory.dart` on ${DateTime.now().toIso8601String().substring(0, 10)}. Do not edit by hand: run it again.')
    ..writeln()
    ..writeln('What each column counts:')
    ..writeln()
    ..writeln('- **onTap**: every `onTap:` in the file, whatever it is passed to.')
    ..writeln('- **pressable**: uses of `Pressable`, the one widget nearly every button ends in.')
    ..writeln('- **material**: Material buttons, switches and menu items (focusable already).')
    ..writeln('- **raw tap**: `GestureDetector`, `InkWell` or `Listener` taking a tap directly. These are the ones to convert or to list with a reason.')
    ..writeln('- **overlay**: dialogs, sheets, menus and overlay entries.')
    ..writeln('- **text box**, **hover** (mouse-only behaviour), **drag** (drags and sliders), **long press** (and secondary tap).')
    ..writeln('- **arrow keys**, **key handler**: places that already read the keyboard.')
    ..writeln('- **autofocus**, **focus node**: places that already manage focus.')
    ..writeln('- **passed over**: `focusable: false`, a control a D-pad skips on purpose (each one is listed with its reason in `test/dpad/guard_test.dart`).')
    ..writeln();

  int count(List<Hit> hits, String kind) => hits.where((h) => h.kind == kind).length;
  final totals = {for (final c in _columns) c: all.values.fold<int>(0, (n, hits) => n + count(hits, c))};
  final lineCount = all.keys.fold<int>(0, (n, f) => n + File(f).readAsLinesSync().length);

  out
    ..writeln('## Totals')
    ..writeln()
    ..writeln('${all.length} files, $lineCount lines.')
    ..writeln()
    ..writeln('| ${_columns.join(' | ')} |')
    ..writeln('|${_columns.map((_) => '---:').join('|')}|')
    ..writeln('| ${_columns.map((c) => totals[c]).join(' | ')} |')
    ..writeln();

  out
    ..writeln('## By file')
    ..writeln()
    ..writeln('| Phase | File | Lines | ${_columns.join(' | ')} |')
    ..writeln('|---:|---|---:|${_columns.map((_) => '---:').join('|')}|');
  final files = all.keys.toList()..sort((a, b) => phaseOf(a) != phaseOf(b) ? phaseOf(a).compareTo(phaseOf(b)) : a.compareTo(b));
  for (final f in files) {
    final hits = all[f]!;
    out.writeln('| ${phaseOf(f) == 0 ? '?' : phaseOf(f)} | `$f` | ${File(f).readAsLinesSync().length} | ${_columns.map((c) => count(hits, c) == 0 ? '' : '${count(hits, c)}').join(' | ')} |');
  }
  out.writeln();

  for (final kind in const ['raw tap', 'passed over', 'overlay', 'text box', 'hover', 'drag', 'long press', 'arrow keys', 'autofocus']) {
    out
      ..writeln('## Every "$kind"')
      ..writeln();
    for (final f in files) {
      final hits = all[f]!.where((h) => h.kind == kind).toList();
      if (hits.isEmpty) continue;
      out.writeln('**`$f`** (phase ${phaseOf(f) == 0 ? '?' : phaseOf(f)})');
      out.writeln();
      for (final h in hits) {
        final text = h.text.length > 110 ? '${h.text.substring(0, 110)}…' : h.text;
        out.writeln('- line ${h.line}: `${text.replaceAll('`', "'")}`');
      }
      out.writeln();
    }
  }

  File('docs/dpad/inventory.md')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('docs/dpad/inventory.md: ${all.length} files, ${totals.entries.map((e) => '${e.value} ${e.key}').join(', ')}');
}
